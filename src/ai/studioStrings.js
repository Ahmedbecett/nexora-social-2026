/** يعيد دالة ترجمة مربوطة باللغة (ar أو en). */
export function makeStudioT(lang) {
  const dict = STUDIO_STRINGS[lang] || STUDIO_STRINGS.en;
  const fallback = STUDIO_STRINGS.en;
  return function t(key, vars) {
    let s = dict[key] ?? fallback[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    return s;
  };
}
