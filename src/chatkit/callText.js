/** 8:21 PM بصيغة لغة المستخدم */
export function fmtClock(ts) {
  const d = new Date(ts || Date.now());
  try { return d.toLocaleTimeString(getLang(), { hour: 'numeric', minute: '2-digit' }); }
  catch { return d.toLocaleTimeString(); }
}
