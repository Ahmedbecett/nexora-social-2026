<#
  NEXORA AI by BECETTI — CI-only Native Secret Vault generator
  ------------------------------------------------------------
  Generates the gitignored partial class NativeSecretVault.g.cs from an
  environment variable (MG_ADS_SECRET_KEY) during private/CI Windows builds.

  Security guarantees:
    - Never echoes or logs the secret key.
    - Encrypts the secret with a random per-build AES-256-CBC key/IV inside
      native code so no plaintext PEM/Base64 key appears in JSON, HTML, JS,
      or source control.
    - Caller MUST delete NativeSecretVault.g.cs in a finally block right after
      building NexoraWindows.exe.
#>
[CmdletBinding()]
param(
  [string]$OutputFile = (Join-Path $PSScriptRoot '..\host\NexoraWindows\Config\NativeSecretVault.g.cs')
)

$ErrorActionPreference = 'Stop'

$rawKey = $env:MG_ADS_SECRET_KEY
if ([string]::IsNullOrWhiteSpace($rawKey)) {
  Write-Host 'MG_ADS_SECRET_KEY environment variable not set; skipping native vault codegen (ads will check DPAPI/env at runtime).'
  exit 0
}

$cleaned = $rawKey.Trim()
$plainBytes = [System.Text.Encoding]::UTF8.GetBytes($cleaned)

$aes = [System.Security.Cryptography.Aes]::Create()
$aes.KeySize = 256
$aes.Mode = [System.Security.Cryptography.CipherMode]::CBC
$aes.Padding = [System.Security.Cryptography.PaddingMode]::PKCS7
$aes.GenerateKey()
$aes.GenerateIV()

try {
  $encryptor = $aes.CreateEncryptor()
  try {
    $cipherBytes = $encryptor.TransformFinalBlock($plainBytes, 0, $plainBytes.Length)
  }
  finally {
    $encryptor.Dispose()
  }

  function Format-ByteArray([byte[]]$Bytes) {
    return (($Bytes | ForEach-Object { "0x{0:X2}" -f $_ }) -join ', ')
  }

  $code = @"
// <auto-generated />
// CI-only gitignored native vault. Deleted immediately after build.
namespace NexoraWindows.Config
{
    internal static partial class NativeSecretVault
    {
        static partial void TryLoadBuildInjectedSecret(ref byte[] cipherBytes, ref byte[] keyBytes, ref byte[] ivBytes)
        {
            cipherBytes = new byte[] { $(Format-ByteArray $cipherBytes) };
            keyBytes = new byte[] { $(Format-ByteArray $aes.Key) };
            ivBytes = new byte[] { $(Format-ByteArray $aes.IV) };
        }
    }
}
"@

  Set-Content -LiteralPath $OutputFile -Value $code -Encoding UTF8
  Write-Host 'Generated ephemeral native secret vault for build (plaintext never logged or committed).'
}
finally {
  [Array]::Clear($plainBytes, 0, $plainBytes.Length)
  $aes.Dispose()
}
