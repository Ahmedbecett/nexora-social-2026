const num = (s) => parseFloat(s);
const attr = (tag, a) => { const m = tag.match(new RegExp(`\\b${a}=(?:"([^"]*)"|\\{([^}]*)\\})`)); return m ? (m[1] ?? m[2]) : null; };
function el2d(tag) {
  const name = tag.match(/^<(\w+)/)[1];
  if (name === 'path') return attr(tag, 'd');
  if (name === 'circle') { const cx = num(attr(tag, 'cx')), cy = num(attr(tag, 'cy')), r = num(attr(tag, 'r')); return `M${cx - r} ${cy}a${r} ${r} 0 1 0 ${2 * r} 0a${r} ${r} 0 1 0 ${-2 * r} 0Z`; }
  if (name === 'rect') {
    const x = num(attr(tag, 'x')), y = num(attr(tag, 'y')), w = num(attr(tag, 'width')), h = num(attr(tag, 'height')), r = num(attr(tag, 'rx') || 0);
    if (!r) return `M${x} ${y}h${w}v${h}h${-w}Z`;
    return `M${x + r} ${y}h${w - 2 * r}a${r} ${r} 0 0 1 ${r} ${r}v${h - 2 * r}a${r} ${r} 0 0 1 ${-r} ${r}h${-(w - 2 * r)}a${r} ${r} 0 0 1 ${-r} ${-r}v${-(h - 2 * r)}a${r} ${r} 0 0 1 ${r} ${-r}Z`;
  }
  return null;
}
