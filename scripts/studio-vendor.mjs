#!/usr/bin/env node
/* ============================================================================
   NEXORA Studio — preview vendor assets
   ----------------------------------------------------------------------------
   Copies the esbuild wasm compiler and builds ESM copies of React so the
   in-browser preview runs generated apps without any CDN dependency for the
   framework itself. Run automatically by `npm run dev` / `npm run build`.
   ============================================================================ */

import { build } from 'esbuild';
import { copyFile, mkdir, writeFile, stat } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const root = process.cwd();
const outDir = join(root, 'public', 'studio');
const vendorDir = join(outDir, 'vendor');

async function newerThan(file, deps) {
  try {
    const s = await stat(file);
    for (const dep of deps) {
      const d = await stat(dep).catch(() => null);
      if (!d || d.mtimeMs > s.mtimeMs) return false;
    }
    return true;
  } catch { return false; }
}

/* Exact-match externals: esbuild's `external` treats strings as prefixes, which
   would turn `react-dom/client` into a bare re-export of itself. */
const exactExternal = (names) => ({
  name: 'exact-external',
  setup(build) {
    build.onResolve({ filter: /.*/ }, (args) => (names.includes(args.path) ? { path: args.path, external: true } : null));
  },
});

const ENTRIES = [
  { name: 'react', code: `export * from 'react'; export { default } from 'react';`, external: [] },
  { name: 'react-dom', code: `export * from 'react-dom'; export { default } from 'react-dom';`, external: ['react'] },
  { name: 'react-dom-client', code: `export * from 'react-dom/client';`, external: ['react', 'react-dom'] },
  { name: 'jsx-runtime', code: `export * from 'react/jsx-runtime';`, external: ['react'] },
];

async function main() {
  await mkdir(vendorDir, { recursive: true });

  const wasmSrc = require.resolve('esbuild-wasm/esbuild.wasm');
  const wasmDest = join(outDir, 'esbuild.wasm');
  if (!existsSync(wasmDest) || !(await newerThan(wasmDest, [wasmSrc]))) {
    await copyFile(wasmSrc, wasmDest);
    console.log('  studio: copied esbuild.wasm');
  }

  const reactPath = require.resolve('react/package.json');
  const reactDomPath = require.resolve('react-dom/package.json');

  for (const entry of ENTRIES) {
    const outfile = join(vendorDir, `${entry.name}.js`);
    if (await newerThan(outfile, [reactPath, reactDomPath])) continue;
    await build({
      stdin: { contents: entry.code, resolveDir: root, loader: 'js' },
      bundle: true,
      format: 'esm',
      outfile,
      platform: 'browser',
      target: ['es2020'],
      plugins: entry.external.length ? [exactExternal(entry.external)] : [],
      define: { 'process.env.NODE_ENV': '"production"', global: 'globalThis' },
      legalComments: 'none',
      minify: true,
      logLevel: 'error',
    });
    console.log('  studio: built vendor/' + entry.name + '.js');
  }

  await writeFile(join(outDir, 'README.txt'),
    'Generated by scripts/studio-vendor.mjs — esbuild wasm + React ESM builds used by the live preview.\n');
}

main().catch((e) => {
  console.error('studio vendor failed:', e.message);
  process.exit(1);
});
